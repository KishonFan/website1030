export function pagePath(locale, page) {
  return `/${locale.code}/${page === 'about' ? '' : page + '/'}`;
}

export function translated(record, field, locale) {
  const value = locale.code === 'zh' ? record[field + 'Zh'] : '';
  return typeof value === 'string' && value.trim() ? value.trim() : record[field];
}
